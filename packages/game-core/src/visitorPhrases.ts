export function visitorPhrase(
  character: string,
  kind: 'messages' | 'games',
  previous: string | undefined,
  sample: number,
): string {
  const phrases = visitorPhrases[character as keyof typeof visitorPhrases]?.[kind] ?? [];
  const choices = phrases.filter((p) => p !== previous);
  return (
    choices[Math.min(choices.length - 1, Math.floor(sample * choices.length))] ??
    'Мне пора по делам.'
  );
}
