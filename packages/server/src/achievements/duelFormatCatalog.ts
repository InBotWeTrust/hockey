export type DuelFormatKey = (typeof DUEL_FORMAT_VARIANTS)[number]['key'];
export function duelFormatKey(kind: string, rules: Record<string, unknown>): DuelFormatKey | null {
  if (kind === 'express_plus') return 'mix';
  if (kind === 'marathon') {
    const window = rules.marathonWindowMs ?? 7000;
    return window === 4000 ? 'marathon-4' : window === 7000 ? 'marathon-7' : null;
  }
  return DUEL_FORMAT_VARIANTS.find((variant) => variant.key === kind)?.key ?? null;
}
interface DuelFormatDefinition {
  id: string;
  title: string;
  description: string;
  photoUrl: string;
  levels: Array<{ target: number; requirement: string; stars: number }>;
}
function task(
  id: string,
  title: string,
  description: string,
  targets: number[],
  rewards: number[],
  requirement: (n: number) => string,
): DuelFormatDefinition {
  return {
    id,
    title,
    description,
    photoUrl: (artwork as Record<string, string>)[id]!,
    levels: targets.map((target, i) => ({
      target,
      requirement: requirement(target),
      stars: rewards[i]!,
    })),
  };
}
