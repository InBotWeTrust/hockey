const duelWord = (n: number) =>
  n % 100 >= 11 && n % 100 <= 14
    ? 'дуэлей'
    : n % 10 === 1
      ? 'дуэль'
      : n % 10 >= 2 && n % 10 <= 4
        ? 'дуэли'
        : 'дуэлей';
const goalWord = (n: number) =>
  n % 100 >= 11 && n % 100 <= 14
    ? 'голов'
    : n % 10 === 1
      ? 'гол'
      : n % 10 >= 2 && n % 10 <= 4
        ? 'гола'
        : 'голов';
